/**
 * ERA 22.1 — ARMOS API ADAPTER
 * ============================
 * Clean service layer between the TC-S Network and the ArmOS Replicator.
 * The OpenAI frontier orchestrator talks to this adapter — ArmOS-specific
 * HTTP calls are never embedded elsewhere in the application.
 *
 * Authority boundaries (critical):
 *   - Engineering results come from the live ArmOS endpoint (/api/engineer),
 *     where Gemini performs manufacturing inference. They are authoritative.
 *   - The Creation Capsule is a UIM/Replicator protocol artifact derived
 *     mechanically from the authoritative ArmOS engineering result — it is
 *     never generated by the orchestrator LLM. Geometry hashes are computed
 *     (sha256) from the actual returned geometry, never invented.
 *   - Execution runs in SIMULATION mode (execution_mode of the capability).
 *     The lifecycle state machine below is the adapter's authoritative
 *     execution state; the marketplace reflects it directly.
 *   - No API secrets or credentials appear in the descriptor, capsule,
 *     provenance, or any client-visible payload.
 */

